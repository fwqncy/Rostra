// Bundles the React Three Fiber tree into one ES module the no-build app can load.
// three.js and growth.js stay external, so the page shares one copy of each.
import { build } from 'esbuild';

const sharedModules = {
  name: 'shared-modules',
  setup(b) {
    b.onResolve({ filter: /^three$/ }, () => ({ path: '/vendor/three/three.module.min.js', external: true }));
    b.onResolve({ filter: /^\/js\// }, (args) => ({ path: args.path, external: true }));
  },
};

await build({
  entryPoints: ['src/index.jsx'],
  outfile: '../../src/Rostra.Api/wwwroot/js/scenes/grove.js',
  bundle: true,
  format: 'esm',
  target: 'es2020',
  minify: true,
  jsx: 'automatic',
  define: { 'process.env.NODE_ENV': '"production"' },
  plugins: [sharedModules],
  legalComments: 'eof',
  banner: { js: '// Generated by client/grove (React Three Fiber). Edit the source there and run `npm run build`.' },
  logLevel: 'info',
});
